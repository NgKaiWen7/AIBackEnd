from pathlib import Path
from typing import Literal, Optional

from ollama import chat
from PIL import Image, ImageDraw
from playwright.sync_api import Error as PlaywrightError
from playwright.sync_api import Playwright, sync_playwright
from playwright.sync_api import TimeoutError as PlaywrightTimeoutError
from pydantic import BaseModel, Field, model_validator

DOWNLOAD_DIR = Path("./vue")
DOWNLOAD_DIR.mkdir(parents=True, exist_ok=True)
MODEL = "qwen3.5:9b"
URL = "https://gemini.rakyatdigital.gov.my/"
PROFILE = "./my_profile"
OUTPUT = Path("./browser_agent_output")
VIEWPORT = {"width": 1280, "height": 720}
OUTPUT.mkdir(exist_ok=True)
DOWNLOAD_BUTTON_SELECTOR = (
    'md-icon-button.download-button[data-aria-label="Download image"]'
)
SYSTEM_PROMPT = """
You are a visual browser automation agent.

Input:
- Current browser screenshot

Return exactly one JSON object:
{"action":"click|input_prompt|wait","x":500,"y":500}

Rules:
- Coordinates are integers from 0 to 1000, normalized to the screenshot.
- click: click a visible target; provide x and y.
- input_prompt: identify the visible prompt input field and return its coordinates.
  Playwright will click the field, enter the user's prompt, and submit it.
- wait: wait 60 seconds; set x and y to 0.
- Act only on visible elements. Return JSON only.

Priorities:
1. If the prompt has not been entered, locate the prompt input field and use "input_prompt".
2. The input field will have Ask a follow-up or Ask Gemini Enterprise
3. After Playwright submits the prompt, use "wait" while the image is generating.
4. If the screenshot shows "Image generated by ..." and the image is still generating,
   use "wait". Do not click the image or download button during generation.
5. Once generation is complete, identify the generated image in the screenshot and click it.
6. The generated image normally will be on top of Image generated by ...
7. Click the generated image to open its preview. Do not click the Download button;
   the Python script will detect and click the download button automatically.
"""


class Action(BaseModel):
    action: Literal["click", "input_prompt", "wait"]
    x: Optional[int] = Field(default=None, ge=0, le=1000)
    y: Optional[int] = Field(default=None, ge=0, le=1000)

    @model_validator(mode="after")
    def check_required_fields(self):
        if self.action in ("click", "input_prompt") and (
            self.x is None or self.y is None
        ):
            raise ValueError(f"{self.action} requires x and y")

        return self


def to_pixels(x, y):
    """Convert the model's 0-1000 coordinates to real viewport pixels."""
    px = int(float(x) / 1000 * VIEWPORT["width"])
    py = int(float(y) / 1000 * VIEWPORT["height"])
    return px, py


def draw_click(path, x, y):
    """Draw a red circle + crosshair at (x, y) and save as <name>_click.png."""
    img = Image.open(path).convert("RGB")
    d = ImageDraw.Draw(img)
    r = 12
    d.ellipse((x - r, y - r, x + r, y + r), outline="red", width=3)
    d.line((x - 20, y, x + 20, y), fill="red", width=2)
    d.line((x, y - 20, x, y + 20), fill="red", width=2)
    d.text((x + 16, y + 16), f"({x}, {y})", fill="red")
    out = Path(path).with_name(Path(path).stem + "_click.png")
    img.save(out)
    return out


def ask_vlm(screenshot, previous_action) -> Action:
    response = chat(
        model=MODEL,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {
                "role": "user",
                "content": (
                    f"PREVIOUS ACTION AND RESULT:\n"
                    f"{previous_action or 'None (first action)'}\n\n"
                    "Choose the next browser action based on the current "
                    "screenshot and previous action result. Do not repeat "
                    "an action that appears to have failed."
                ),
                "images": [str(screenshot)],
            },
        ],
        format=Action.model_json_schema(),
        think=False,
        options={"temperature": 0},
    )

    return Action.model_validate_json(response.message.content)


def execute(page, action: Action, prompt: str):
    try:
        if action.action == "wait":
            page.wait_for_timeout(10_000)
            return True, "waited 10 seconds"

        if action.action == "click":
            x, y = to_pixels(action.x, action.y)
            page.mouse.click(x, y)
            return True, f"clicked ({x}, {y})"

        if action.action == "input_prompt":
            x, y = to_pixels(action.x, action.y)
            page.mouse.click(x, y)
            page.keyboard.insert_text(prompt)
            page.keyboard.press("Enter")
            return (True, f"clicked ({x}, {y}), typed '{prompt}', pressed Enter")
        else:
            return (True, "Action not defined")
    except Exception as exc:
        return True, f"FAILED: {str(exc)[:200]}"


def test_download_buttons(page, prompt_index: int = 1, button_timeout: int = 2500):
    """Click visible download buttons and save downloads before closing context."""
    DOWNLOAD_DIR.mkdir(parents=True, exist_ok=True)
    results = {"found": 0, "downloaded": 0, "failed": 0}
    buttons = page.locator(DOWNLOAD_BUTTON_SELECTOR)

    try:
        buttons.first.wait_for(state="attached", timeout=button_timeout)
        count = buttons.count()
    except PlaywrightTimeoutError:
        return results
    except PlaywrightError as exc:
        print(f"Cannot inspect download button: {type(exc).__name__}: {exc}")
        results["failed"] += 1
        return results

    results["found"] = count
    print(f"Found {count} download button(s).")

    for button_index in range(count):
        button = page.locator(DOWNLOAD_BUTTON_SELECTOR).nth(button_index)
        print(
            f"\nTesting download button {button_index + 1}/{count} "
            f"for prompt {prompt_index}..."
        )
        # Arm the download wait BEFORE clicking. Save only after the event
        # has been captured; avoid a second save operation in an event callback.
        with page.expect_download(timeout=30_000) as download_info:
            button.evaluate("(el) => el.click()")
        download = download_info.value
        filename = Path(download.suggested_filename).name
        if not filename:
            filename = f"image_{button_index + 1}.png"
        save_path = DOWNLOAD_DIR / (
            f"prompt_{prompt_index:03d}_download_{button_index + 1:02d}_{filename}"
        )
        # save_as waits for the download to finish. Keep the BrowserContext
        # alive until this call returns.
        download.save_as(save_path)
        if not save_path.is_file() or save_path.stat().st_size == 0:
            raise RuntimeError("Downloaded file is missing or empty.")
        results["downloaded"] += 1
        print(f"PASS: {save_path} ({save_path.stat().st_size:,} bytes)")
        if page.is_closed():
            print("The source page closed during the download operation.")
            break

    print("\n========== DOWNLOAD TEST SUMMARY ==========")
    print(f"Buttons found:     {results['found']}")
    print(f"Downloads saved:   {results['downloaded']}")
    print(f"Failed/skipped:    {results['failed']}")
    print(f"Output directory:  {DOWNLOAD_DIR}")
    return results


def run(playwright: Playwright, prompts: list[str]):
    DOWNLOAD_DIR.mkdir(parents=True, exist_ok=True)
    OUTPUT.mkdir(parents=True, exist_ok=True)

    # Use Playwright's bundled Chromium rather than the installed branded Chrome.
    # This avoids the branded-browser download/context crash seen in some versions.
    # A separate profile is intentional because the existing profile was used by Chrome.
    context = playwright.chromium.launch_persistent_context(
        user_data_dir=PROFILE,
        headless=False,
        accept_downloads=True,
        args=["--disable-blink-features=AutomationControlled"],
    )

    page = context.pages[0] if context.pages else context.new_page()

    # Keep another tab open so a source page closing alone does not end the session.
    keepalive_page = context.new_page()
    keepalive_page.goto("about:blank")
    page.bring_to_front()

    try:
        page.goto(URL, wait_until="domcontentloaded")
        input("When the website is ready, press Enter...")

        for index, prompt in enumerate(prompts, start=1):
            print(f"\nPrompt {index}/{len(prompts)}")
            downloaded = False
            failed = False
            previous_action = None

            for step in range(40):
                if page.is_closed():
                    print("Browser page closed; reopening Gemini in a new tab.")
                    try:
                        page = context.new_page()
                        page.goto(URL, wait_until="domcontentloaded", timeout=60_000)
                        page.bring_to_front()
                        page.wait_for_timeout(1500)
                    except PlaywrightError as exc:
                        print(f"Could not reopen Gemini: {type(exc).__name__}: {exc}")
                        return

                screenshot = OUTPUT / f"prompt_{index:03d}_step_{step:03d}.png"

                try:
                    page.screenshot(path=str(screenshot))
                except PlaywrightError as exc:
                    print(f"Screenshot failed: {exc}")
                    return

                action = ask_vlm(screenshot, previous_action)
                print(f"Step {step}: {action}")

                if action.action == "click":
                    x, y = to_pixels(action.x, action.y)
                    marked = draw_click(screenshot, x, y)
                    print(f"  click marker saved: {marked}")

                success, status = execute(page, action, prompt)
                print(status)
                previous_action = f"{action}; {status}"

                # Let preview controls or generated content finish rendering.
                page.wait_for_timeout(2000)

                # The agent clicks the generated image to open its preview.
                # Once the download control is attached, use the standalone
                # Playwright download function rather than extracting image blobs.
                if action.action == "click":
                    download_buttons = page.locator(DOWNLOAD_BUTTON_SELECTOR)
                    if download_buttons.count() > 0:
                        download_result = test_download_buttons(
                            page, prompt_index=index
                        )
                        if download_result["downloaded"] > 0:
                            downloaded = True
                            print(f"Prompt {index} completed.")
                            try:
                                page.keyboard.press("Escape")
                                page.wait_for_timeout(500)

                                # Start a new Gemini chat after downloading.
                                page.get_by_role("link", name="New chat").click()
                                page.wait_for_timeout(1000)
                            except PlaywrightError:
                                pass
                            break

                        if download_result["found"] > 0:
                            previous_action = (
                                f"Download button was present but the download failed: "
                                f"{download_result}"
                            )

                if not success:
                    print("Action failed; stopping.")
                    failed = True
                    break

            if downloaded:
                print("Moving to the next prompt...")
                continue

            if failed:
                return

            print(
                f"Prompt {index} did not produce a saved image "
                "within the step limit. Stopping."
            )
            break

    finally:
        try:
            context.close()
        except PlaywrightError as exc:
            # A page/browser may already have closed itself; don't mask a successful download.
            if "closed" not in str(exc).lower():
                raise


if __name__ == "__main__":
    from vue_nuxt_memory_prompts import build_prompts

    prompts = build_prompts()

    with sync_playwright() as playwright:
        run(playwright, prompts)
