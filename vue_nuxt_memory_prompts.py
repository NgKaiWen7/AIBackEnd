def build_prompts(sections=None, include_style=True):
    """Return prompts in card order. `sections` may be None, a string, or an iterable of section names."""
    selected = None if sections is None else ({sections} if isinstance(sections, str) else set(sections))
    result = []
    for card in CARD_PROMPTS:
        if selected is not None and card["section"] not in selected:
            continue
        result.append((STYLE_PROMPT + "\n\n" + card["prompt"]) if include_style else card["prompt"])
    return result

if __name__ == "__main__":
    print(f"{len(CARD_PROMPTS)} cards across {len(set(c['section'] for c in CARD_PROMPTS))} sections")
    for card in CARD_PROMPTS:
        print(f"{card['id']:03d}. [{card['section']}] {card['title']}")
